#!/usr/bin/env node
/**
 * eval-llm — promptfoo LLM Eval executor for GS scenarios.
 *
 *   node scripts/harness/cli.mjs eval-llm --generate   Generate promptfoo config + prompt files
 *   node scripts/harness/cli.mjs eval-llm --check      Validate the generated config (no LLM call)
 *   node scripts/harness/cli.mjs eval-llm --list       List scenarios that would be evaluated
 *   node scripts/harness/cli.mjs eval-llm              Run promptfoo eval (needs PALLAS_LLM_API_KEY)
 *
 * The generator reads harness/scenarios/scenarios.json (GS-001..GS-015), writes
 * one prompt file per scenario under harness/promptfoo/prompts/, and emits
 * promptfooconfig.yaml. Actual LLM execution is triggered via promptfoo and
 * requires an API key supplied through the PALLAS_LLM_API_KEY env var (never
 * committed).
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { spawnSync } from 'node:child_process';

const ROOT = resolve(import.meta.dirname, '..', '..');
const SCENARIOS_FILE = resolve(ROOT, 'harness', 'scenarios', 'scenarios.json');
const OUT_DIR = resolve(ROOT, 'harness', 'promptfoo');
const PROMPTS_DIR = resolve(OUT_DIR, 'prompts');
const CONFIG_FILE = resolve(OUT_DIR, 'promptfooconfig.yaml');

function loadScenarios() {
  if (!existsSync(SCENARIOS_FILE)) return [];
  try {
    return JSON.parse(readFileSync(SCENARIOS_FILE, 'utf-8')).scenarios || [];
  } catch {
    return [];
  }
}

export function buildPrompt(scenario) {
  const lines = [`# Eval Scenario ${scenario.id}: ${scenario.name}`];
  if (scenario.description) lines.push('', scenario.description);
  if (scenario.mustDo?.length) {
    lines.push('', '## MUST do');
    for (const x of scenario.mustDo) lines.push(`- ${x}`);
  }
  if (scenario.mustNotDo?.length) {
    lines.push('', '## MUST NOT do');
    for (const x of scenario.mustNotDo) lines.push(`- ${x}`);
  }
  if (scenario.scoring && typeof scenario.scoring === 'object') {
    lines.push('', '## Scoring');
    for (const [k, v] of Object.entries(scenario.scoring)) lines.push(`- ${k}: ${v}`);
  }
  return lines.join('\n');
}

export function generate({ rootDir = ROOT } = {}) {
  const scenarios = loadScenarios();
  mkdirSync(PROMPTS_DIR, { recursive: true });

  const promptRefs = [];
  for (const s of scenarios) {
    const key = `prompts/${s.id.toLowerCase()}.txt`;
    writeFileSync(resolve(PROMPTS_DIR, `${s.id.toLowerCase()}.txt`), buildPrompt(s));
    promptRefs.push({ id: s.id, file: key });
  }

  const yaml = [
    '# Generated by `harness eval-llm --generate` — do not edit by hand.',
    `# Re-run the generator after changing harness/scenarios/scenarios.json.`,
    'description: PallasTrade AI Coding Eval (GS scenarios)',
    'prompts:',
    ...promptRefs.map((p) => `  - file://${p.file}`),
    'providers:',
    '  - id: openai:gpt-4o',
    '    config:',
    '      apiKeyEnvVar: PALLAS_LLM_API_KEY',
    'tests:',
    ...promptRefs.map((p) => `  - vars:\n      scenario: ${p.id}`),
    'defaultTest:',
    '  assert:',
    '  - type: contains',
    '    value: "PallasTrade"',
    '    description: "response should be PallasTrade-aware"',
    '',
  ].join('\n');

  writeFileSync(CONFIG_FILE, yaml);
  return { scenarios: promptRefs.length, config: CONFIG_FILE };
}

export function check({ rootDir = ROOT } = {}) {
  const problems = [];
  if (!existsSync(CONFIG_FILE)) problems.push(`missing ${CONFIG_FILE}`);
  if (!existsSync(PROMPTS_DIR)) problems.push(`missing ${PROMPTS_DIR}`);

  const scenarios = loadScenarios();
  for (const s of scenarios) {
    const f = resolve(PROMPTS_DIR, `${s.id.toLowerCase()}.txt`);
    if (!existsSync(f)) problems.push(`missing prompt file for ${s.id}`);
  }
  if (problems.length === 0) {
    console.log(`✅ eval-llm: config valid — ${scenarios.length} scenario prompt(s) generated.`);
    return { ok: true, count: scenarios.length };
  }
  for (const p of problems) console.log(`❌ ${p}`);
  return { ok: false, count: scenarios.length };
}

export function list({ rootDir = ROOT } = {}) {
  const scenarios = loadScenarios();
  for (const s of scenarios) console.log(`${s.id}\t${s.name}`);
  return { count: scenarios.length };
}

export function run({ rootDir = ROOT, args = [] } = {}) {
  if (args.includes('--generate')) {
    const { scenarios, config } = generate({ rootDir });
    console.log(`✅ eval-llm: generated ${scenarios} scenario prompt(s) + ${config}`);
    return;
  }
  if (args.includes('--check')) {
    check({ rootDir });
    return;
  }
  if (args.includes('--list')) {
    list({ rootDir });
    return;
  }

  // Default: run promptfoo eval.
  const preflight = check({ rootDir });
  if (!preflight.ok) {
    console.error('❌ eval-llm: run --generate first, then retry.');
    process.exitCode = 1;
    return;
  }
  if (!process.env.PALLAS_LLM_API_KEY) {
    console.error(
      '❌ eval-llm: PALLAS_LLM_API_KEY is not set. Provide an LLM API key via env var (never commit it).',
    );
    process.exitCode = 1;
    return;
  }
  const res = spawnSync('npx', ['promptfoo', 'eval', '-c', CONFIG_FILE], {
    stdio: 'inherit',
    cwd: ROOT,
    env: process.env,
  });
  if (res.status !== 0) process.exitCode = res.status ?? 1;
}
